"""Write frontend/lib/flags/registry.gen.ts from the Python flag and config registries.

    cd backend && python -m scripts.gen_flag_types

tests/test_flag_registry.py fails when the committed file differs from render().
"""

from __future__ import annotations

import json
from pathlib import Path

from feature_flags.config_registry import CONFIGS
from feature_flags.registry import FLAGS, LEGACY_KEYS

OUTPUT = Path(__file__).resolve().parents[2] / "frontend" / "lib" / "flags" / "registry.gen.ts"
TS_TYPES = {"int": "number", "float": "number", "bool": "boolean", "string": "string"}


def _quote(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _union(name: str, keys: list[str]) -> str:
    return f"export type {name} =\n" + "\n".join(f"  | {_quote(key)}" for key in keys) + ";\n"


def _record(name: str, type_: str, entries: dict[str, str]) -> str:
    body = "\n".join(f"  {_quote(key)}: {value}," for key, value in entries.items())
    return f"export const {name}: {type_} = {{\n{body}\n}};\n"


def _config_type(key: str) -> str:
    config = CONFIGS[key]
    if config.kind == "enum":
        return " | ".join(_quote(choice) for choice in config.choices)
    return TS_TYPES[config.kind]


def render() -> str:
    flag_keys = list(FLAGS)
    config_keys = list(CONFIGS)
    config_values = "\n".join(f"  {_quote(key)}: {_config_type(key)};" for key in config_keys)
    sections = [
        "// Generated by backend/scripts/gen_flag_types.py from backend/feature_flags/registry.py and\n"
        "// config_registry.py. Do not edit: change the Python registry and run\n"
        "// `cd backend && python -m scripts.gen_flag_types`.\n",
        _union("FlagKey", flag_keys),
        _union("LegacyFlagKey", [key for key in flag_keys if key in LEGACY_KEYS]),
        _union("ConfigKey", config_keys),
        f"export interface ConfigValues {{\n{config_values}\n}}\n",
        _record("FLAG_DEFAULTS", "Record<FlagKey, boolean>",
                {key: json.dumps(flag.default) for key, flag in FLAGS.items()}),
        _record("CONFIG_DEFAULTS", "ConfigValues",
                {key: json.dumps(config.default) for key, config in CONFIGS.items()}),
        _record("FLAG_LIVE_UPDATE", "Record<FlagKey, 'immediate' | 'next_navigation'>",
                {key: _quote(flag.live_update) for key, flag in FLAGS.items()}),
        _record("FLAG_PARENTS", "Record<FlagKey, FlagKey | null>",
                {key: _quote(flag.parent) if flag.parent else "null" for key, flag in FLAGS.items()}),
    ]
    return "\n".join(sections)


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render())
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
