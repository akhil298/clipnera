"""Write the asset guides an editing model reads: what each asset is, measured.

Two Markdown files under ``static/motion``:

* ``ASSETS.md`` -- what renders can use (shipped with the backend): the curated
  and synthesised sound effects, hook graphics, bundled fonts and branding.
* ``LIBRARY.md`` -- the local creator library (``library/``, gitignored, never
  on servers), for picking what to promote into the shipped set.

Facts come from probing (``catalog.json`` and the SFX manifests); audio is also
listened to in numbers: loudness, where its peak is, its shape (a hit, a rise,
a sustained bed, music) and how bright it is, plus the tempo of music. Names
and folders give the rest; nothing is guessed beyond that.

    cd backend && venv/bin/python -m scripts.describe_motion_assets
"""

from __future__ import annotations

import json
import os
import re
import subprocess
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import numpy as np

BACKEND = Path(__file__).resolve().parents[1]
MOTION = BACKEND / "static" / "motion"
SAMPLE_RATE = 16000
# Music is described from its first minute; a long track is the same groove.
LISTEN_SECONDS = 60.0
FRAME = 0.05


def _decode(path: Path) -> np.ndarray:
    raw = subprocess.run(
        ["ffmpeg", "-v", "error", "-t", str(LISTEN_SECONDS), "-i", str(path), "-vn", "-ac", "1",
         "-ar", str(SAMPLE_RATE), "-f", "f32le", "pipe:1"],
        capture_output=True,
    ).stdout
    return np.frombuffer(raw, np.float32)


def listen(path: Path) -> dict:
    """Loudness, peak time, shape, brightness (and tempo for music) of an audio file."""
    samples = _decode(path)
    if samples.size < SAMPLE_RATE // 20:
        return {}
    hop = int(SAMPLE_RATE * FRAME)
    frames = samples[: len(samples) // hop * hop].reshape(-1, hop)
    envelope = np.sqrt((frames ** 2).mean(axis=1)) + 1e-9
    seconds = len(samples) / SAMPLE_RATE
    peak = int(envelope.argmax())
    third = max(1, len(envelope) // 3)
    first, last = envelope[:third].mean(), envelope[-third:].mean()
    if seconds > 20:
        shape = "music or bed"
    elif peak < len(envelope) * 0.25 and last < envelope[peak] * 0.3:
        shape = "hit (strikes then decays)"
    elif last > first * 2 and peak > len(envelope) * 0.6:
        shape = "rise (builds to the end)"
    elif first > last * 2 and peak < len(envelope) * 0.4:
        shape = "fall (starts strong, fades)"
    else:
        shape = "sustained"
    spectrum = np.abs(np.fft.rfft(samples[: SAMPLE_RATE * 10] * np.hanning(min(len(samples), SAMPLE_RATE * 10))))
    freqs = np.fft.rfftfreq(min(len(samples), SAMPLE_RATE * 10), 1 / SAMPLE_RATE)
    centroid = float((spectrum * freqs).sum() / max(1e-9, spectrum.sum()))
    tone = "dark" if centroid < 900 else "bright" if centroid > 2200 else "mid"
    facts = {
        "loudness_dbfs": round(20 * float(np.log10(np.sqrt((samples ** 2).mean()) + 1e-9)), 1),
        "peak_s": round(peak * FRAME, 2),
        "shape": shape,
        "tone": tone,
    }
    if seconds > 20:
        facts["bpm"] = _tempo(envelope)
    return facts


def _tempo(envelope: np.ndarray) -> int | None:
    """Beats per minute from the autocorrelation of the onset strength, 60-180."""
    onsets = np.maximum(0.0, np.diff(envelope))
    if onsets.size < 100 or not onsets.any():
        return None
    onsets = onsets - onsets.mean()
    corr = np.correlate(onsets, onsets, mode="full")[onsets.size - 1:]
    lags = np.arange(int(60 / 180 / FRAME), int(60 / 60 / FRAME) + 1)
    best = lags[int(np.argmax(corr[lags]))]
    return int(round(60 / (best * FRAME)))


def _clock(seconds: float | None) -> str:
    if not seconds:
        return ""
    return f"{seconds:.2f}s" if seconds < 10 else f"{int(seconds // 60)}:{int(seconds % 60):02d}"


def _cell(text: object) -> str:
    return str(text if text is not None else "").replace("|", "/").replace("\n", " ")


def _licence(rel: str) -> str:
    low = rel.lower()
    if "mixkit" in low:
        return "Mixkit free licence"
    if "pixabay" in low or re.search(r"-\d{5,6}( \(\d\))?\.(mp3|wav)$", low):
        return "Pixabay content licence"
    if "vecteezy" in low:
        return "Vecteezy free licence (credit required)"
    if "kevin macleod" in low:
        return "CC BY 4.0, credit Kevin MacLeod"
    if re.search(r"youtube audio library|royalty.?free|no.?copyright|copyright.?free|creative commons", low):
        return "claimed free by source, verify"
    return "creator pack, verify before export"


# ---------------------------------------------------------------- shipped assets


def shipped_guide() -> str:
    lines = [
        "# Motion assets that renders can use",
        "",
        "Generated by `scripts/describe_motion_assets.py`; do not edit by hand. Everything here ships with",
        "the backend under `backend/static/motion/`. Refer to sounds by their **name** exactly as listed.",
        "",
        "How to read the sound tables: *length* is the whole file; *peak* is where its loudest moment falls,",
        "the point lined up with the event it marks (a rise is lined up by its end instead); *shape* says",
        "how it moves (a hit strikes and decays, a rise builds to its end, a bed sustains); *tone* is how",
        "bright it sounds; *loudness* is its average level in dBFS (more negative is quieter).",
        "",
    ]
    lines += _curated_sounds()
    lines += _synth_sounds()
    lines += _hook_graphics()
    lines += _fonts()
    lines += _branding()
    return "\n".join(lines) + "\n"


def _curated_sounds() -> list[str]:
    manifest = json.loads((MOTION / "sfx" / "manifest.json").read_text())
    uses = {
        "pop": "a card or sticker appears", "click": "each list item ticks", "soft_click": "a quiet UI touch",
        "whoosh": "a slide or layout change", "whoosh_short": "a quick swipe, a tag sliding in",
        "ding": "a figure lands, a call to action", "cash": "a money figure lands", "tick": "a counter running",
        "boom": "a big reveal or hard cut", "riser": "build-up into a moment (ends on it)",
    }
    rows = ["## Curated sound effects (`sfx/`), used by motion graphics", "",
            "| Name | Used for | Length | Peak | Shape | Tone | Loudness | Licence |",
            "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for name, entry in manifest.items():
        heard = listen(MOTION / "sfx" / entry["file"])
        rows.append(f"| `{name}` | {uses.get(name, '')} | {_clock(entry['seconds'])} | {entry['peak']:.2f}s | "
                    f"{heard.get('shape', '')} | {heard.get('tone', '')} | {heard.get('loudness_dbfs', '')} | "
                    f"{_cell(entry.get('licence'))} |")
    return rows + [""]


def _synth_sounds() -> list[str]:
    path = MOTION / "sfx" / "synth" / "manifest.json"
    if not path.exists():
        return []
    manifest = json.loads(path.read_text())
    rows = ["## Synthesised sound effects (`sfx/synth/`)", "",
            f"{len(manifest)} original sounds made in code (`scripts/build_synth_sfx.py`); free of any third-party rights.",
            ""]
    by_category: dict[str, list[tuple[str, dict]]] = {}
    for name, entry in manifest.items():
        by_category.setdefault(entry.get("category") or "other", []).append((name, entry))
    for category in sorted(by_category):
        rows += [f"### {category}", "", "| Name | Length | Peak | Shape | Tone | Loudness | Tags |",
                 "| --- | --- | --- | --- | --- | --- | --- |"]
        items = by_category[category]
        heard = list(ThreadPoolExecutor(8).map(lambda item: listen(MOTION / "sfx" / "synth" / item[1]["file"]), items))
        for (name, entry), facts in zip(items, heard):
            rows.append(f"| `{name}` | {_clock(entry.get('seconds'))} | {float(entry.get('peak') or 0):.2f}s | "
                        f"{facts.get('shape', '')} | {facts.get('tone', '')} | "
                        f"{entry.get('loudness_db', facts.get('loudness_dbfs', ''))} | {', '.join(entry.get('tags') or [])} |")
        rows.append("")
    return rows


def _hook_graphics() -> list[str]:
    folder = MOTION / "hook_graphics"
    manifest_path = folder / "manifest.json"
    if not manifest_path.exists():
        return []
    rows = ["## Hook bridge graphics (`hook_graphics/`)", "",
            "Full-frame clips played across the cut from the teaser into the clip, each with its own sound.", "",
            "| File | Length | Size | Alpha |", "| --- | --- | --- | --- |"]
    for video in sorted(folder.glob("*.mp4")):
        info = _probe(video)
        rows.append(f"| `{video.name}` | {_clock(info.get('duration'))} | {info.get('size', '')} | {info.get('alpha', '')} |")
    rows += ["", "| Sound | Length | Shape | Tone | Loudness |", "| --- | --- | --- | --- | --- |"]
    for sound in sorted((folder / "sfx").glob("*.wav")):
        facts = listen(sound)
        rows.append(f"| `{sound.name}` | {_clock(_probe(sound).get('duration'))} | {facts.get('shape', '')} | "
                    f"{facts.get('tone', '')} | {facts.get('loudness_dbfs', '')} |")
    return rows + [""]


def _fonts() -> list[str]:
    folder = MOTION / "fonts"
    rows = ["## Bundled fonts (`fonts/`)", "", "Each has its licence file beside it.", "",
            "| File | Licence file |", "| --- | --- |"]
    licences = {p.name.lower(): p.name for p in folder.glob("LICENSE-*")}
    for font in sorted(p for p in folder.iterdir() if p.suffix.lower() in (".ttf", ".otf")):
        key = re.sub(r"[^a-z]", "", font.stem.lower().split("-")[0])
        match = next((name for low, name in licences.items() if key.startswith(re.sub(r"[^a-z]", "", low[8:-4]))), "")
        rows.append(f"| `{font.name}` | {match} |")
    return rows + [""]


def _branding() -> list[str]:
    folder = MOTION / "branding"
    if not folder.exists():
        return []
    rows = ["## Clipnera branding (`branding/`)", "", "Intro, outro end cards and the watermark, added to Free exports.", "",
            "| File | Length | Size |", "| --- | --- | --- |"]
    for media in sorted(p for p in folder.rglob("*") if p.suffix.lower() in (".mp4", ".mov")):
        info = _probe(media)
        rows.append(f"| `{media.relative_to(folder)}` | {_clock(info.get('duration'))} | {info.get('size', '')} |")
    return rows + [""]


def _probe(path: Path) -> dict:
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration:stream=width,height,pix_fmt",
                          "-of", "json", str(path)], capture_output=True, text=True).stdout
    data = json.loads(out or "{}")
    video = next((s for s in data.get("streams", []) if s.get("width")), {})
    return {
        "duration": float((data.get("format") or {}).get("duration") or 0),
        "size": f"{video['width']}x{video['height']}" if video else "",
        "alpha": "yes" if "a" in str(video.get("pix_fmt", "")).replace("yuv", "") else "no",
    }


# ---------------------------------------------------------------- local library


def library_guide() -> str:
    catalog = json.loads((MOTION / "catalog.json").read_text())
    entries = [
        entry for entry in catalog["assets"]
        if entry["path"].startswith("static/motion/library/") and (BACKEND / entry["path"]).exists()
        and not entry["path"].startswith("static/motion/library/reference/")
    ]
    audio = [entry for entry in entries if entry["file_type"] == "audio"]
    heard = dict(zip((e["path"] for e in audio), ThreadPoolExecutor(8).map(lambda e: listen(BACKEND / e["path"]), audio)))
    lines = [
        "# Local creator library",
        "",
        "Generated by `scripts/describe_motion_assets.py`; do not edit by hand.",
        "",
        "**Local only.** These files live in `backend/static/motion/library/` (gitignored) and are never on the",
        "servers, so no render can use them. To use one, promote it into the shipped set (see `ASSETS.md`)",
        "after checking its licence. Reference reels (`library/reference/`) are for testing and are not listed.",
        "Cleaned by `scripts/clean_motion_library.py` (duplicates, rips, meme audio and unusable font formats removed).",
        "",
        f"{len(entries)} files. Licence is inferred from the source name and must be checked before export.",
        "",
    ]
    by_category: dict[str, list[dict]] = {}
    for entry in entries:
        by_category.setdefault(entry["category"], []).append(entry)
    for category in sorted(by_category):
        items = sorted(by_category[category], key=lambda e: e["path"])
        lines += [f"## {category.replace('_', ' ')} ({len(items)})", ""]
        fonts = [e for e in items if e["file_type"] == "font"]
        if fonts:
            families = sorted({re.split(r"[-_ ]", e["name"].strip())[0].title() for e in fonts})
            lines += [f"{len(fonts)} font files, {len(families)} families: " + ", ".join(families), ""]
        sounds = [e for e in items if e["file_type"] == "audio"]
        if sounds:
            lines += ["| Name | File | Length | Shape | Tone | Loudness | BPM | Licence |",
                      "| --- | --- | --- | --- | --- | --- | --- | --- |"]
            for e in sounds:
                facts = heard.get(e["path"], {})
                lines.append(f"| {_cell(e['name'])} | `{e['path'].removeprefix('static/motion/library/')}` | "
                             f"{_clock((e.get('media') or {}).get('duration_seconds'))} | {facts.get('shape', '')} | "
                             f"{facts.get('tone', '')} | {facts.get('loudness_dbfs', '')} | {facts.get('bpm') or ''} | "
                             f"{_licence(e['path'])} |")
            lines.append("")
        visuals = [e for e in items if e["file_type"] in ("video", "image")]
        if visuals:
            lines += ["| Name | File | Type | Length | Size | Alpha | Has sound | Licence |",
                      "| --- | --- | --- | --- | --- | --- | --- | --- |"]
            for e in visuals:
                media = e.get("media") or {}
                video = media.get("video") or {}
                size = f"{video.get('width')}x{video.get('height')}" if video.get("width") else ""
                green = " (green screen)" if re.search(r"green.?screen|chroma", e["path"], re.IGNORECASE) else ""
                lines.append(
                    f"| {_cell(e['name'])}{green} | `{e['path'].removeprefix('static/motion/library/')}` | "
                    f"{e['file_type']} | {_clock(media.get('duration_seconds')) if e['file_type'] == 'video' else ''} | "
                    f"{size} | {'yes' if video.get('has_alpha') else 'no'} | {'yes' if media.get('audio') else 'no'} | "
                    f"{_licence(e['path'])} |")
            lines.append("")
        other = [e for e in items if e["file_type"] not in ("audio", "video", "image", "font")]
        if other:
            lines += [f"Other files: " + ", ".join(f"`{e['path'].removeprefix('static/motion/library/')}`" for e in other), ""]
    return "\n".join(lines) + "\n"


def main() -> None:
    os.chdir(BACKEND)
    (MOTION / "ASSETS.md").write_text(shipped_guide(), encoding="utf-8")
    print("wrote", MOTION / "ASSETS.md")
    (MOTION / "LIBRARY.md").write_text(library_guide(), encoding="utf-8")
    print("wrote", MOTION / "LIBRARY.md")


if __name__ == "__main__":
    main()
