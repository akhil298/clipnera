"""Search the locally generated motion asset catalog for editing candidates."""

from __future__ import annotations

import json
import hashlib
import re
import shutil
import zipfile
from pathlib import Path
from pathlib import PurePosixPath
from typing import Any

BACKEND = Path(__file__).resolve().parent.parent
ASSET_ROOT = BACKEND / "static" / "motion"
CATALOG = ASSET_ROOT / "catalog.json"
EXTRACTED = ASSET_ROOT / "extracted"
_TOKEN = re.compile(r"[a-z0-9]+")
_SAFE_SUFFIX = re.compile(r"\.[a-zA-Z0-9]{1,10}$")


def search_assets(query: str, category: str | None = None, limit: int = 10) -> list[dict[str, Any]]:
    """Return ranked catalog entries with paths and preview/timing context.

    The catalog is generated by ``scripts/index_motion_library.py``. Missing
    or invalid catalogs raise explicit errors rather than returning no matches.
    """
    terms = set(_TOKEN.findall(query.lower()))
    if not terms:
        raise ValueError("query must contain at least one searchable word")
    if not 1 <= limit <= 50:
        raise ValueError("limit must be between 1 and 50")
    data = json.loads(CATALOG.read_text(encoding="utf-8"))
    ranked: list[tuple[int, dict[str, Any]]] = []
    for asset in data["assets"]:
        if category and asset.get("category") != category:
            continue
        fields = [
            asset.get("name", ""),
            asset.get("category", ""),
            asset.get("description", ""),
            *asset.get("tags", []),
        ]
        manifest_metadata = asset.get("manifest_metadata", {})
        if isinstance(manifest_metadata, dict):
            fields.extend(str(value) for value in manifest_metadata.values())
        available = set(_TOKEN.findall(" ".join(map(str, fields)).lower()))
        score = len(terms & available)
        if score:
            ranked.append((score, asset))
    ranked.sort(
        key=lambda item: (
            -item[0],
            item[1].get("retrieval_status") == "extract_archive_member_before_use",
            item[1].get("name", "").casefold(),
            item[1].get("path", ""),
        )
    )
    return [asset for _, asset in ranked[:limit]]


def prompt_context(query: str, category: str | None = None, limit: int = 8) -> str:
    """Serialize concise candidate metadata for an editing-model prompt."""
    matches = search_assets(query, category=category, limit=limit)
    fields = (
        "id", "name", "path", "source_path", "category", "tags", "description", "media",
        "time_slices", "preview_sheet", "license", "license_status", "manifest_metadata",
    )
    candidates = [{key: asset[key] for key in fields if key in asset} for asset in matches]
    return json.dumps(candidates, ensure_ascii=False, separators=(",", ":"))


def resolve_asset(asset: dict[str, Any]) -> Path:
    """Resolve a catalog result to a local file, extracting ZIP members safely.

    Extracted members are cached under the motion-assets root and ignored by
    the catalog indexer. ZIP paths are validated and never extracted wholesale.
    """
    relative = asset.get("path")
    if not isinstance(relative, str) or not relative:
        raise ValueError("asset must include a catalog path")
    archive_marker = "!/"
    if archive_marker not in relative:
        path = _inside_asset_root(BACKEND / relative)
        if not path.is_file():
            raise FileNotFoundError(f"Catalog asset is missing: {relative}")
        return path

    archive_relative, member_name = relative.split(archive_marker, 1)
    member = PurePosixPath(member_name)
    if member.is_absolute() or not member.parts or any(part in {"", ".", ".."} for part in member.parts):
        raise ValueError("archive member path is not a safe relative path")
    archive = _inside_asset_root(BACKEND / archive_relative)
    if not archive.is_file():
        raise FileNotFoundError(f"Catalog archive is missing: {archive_relative}")

    suffix = member.suffix if _SAFE_SUFFIX.fullmatch(member.suffix) else ""
    key = hashlib.sha256(f"{archive_relative}!/{member_name}".encode("utf-8")).hexdigest()
    target = EXTRACTED / key[:2] / f"{key}{suffix}"
    if target.is_file():
        return target
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_suffix(target.suffix + ".tmp")
    try:
        with zipfile.ZipFile(archive) as zipped:
            info = zipped.getinfo(member_name)
            if info.is_dir():
                raise ValueError("archive member is a directory, not an asset")
            with zipped.open(info) as source, temporary.open("wb") as destination:
                shutil.copyfileobj(source, destination)
    except Exception:
        temporary.unlink(missing_ok=True)
        raise
    temporary.replace(target)
    return target


def _inside_asset_root(path: Path) -> Path:
    resolved = path.resolve()
    try:
        resolved.relative_to(ASSET_ROOT.resolve())
    except ValueError as error:
        raise ValueError("catalog paths must stay inside the motion asset root") from error
    return resolved
